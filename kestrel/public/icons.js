export function icon(name, size = null) {
  const s = size ? ` width="${size}" height="${size}"` : "";
  return `<svg viewBox="0 0 24 24"${s} fill="none" stroke="currentColor" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${P[name] || P.dot}</svg>`;
}

/** Fill every <span data-icon="name"> inside root. */
export function paintIcons(root = document) {
  for (const el of root.querySelectorAll("[data-icon]")) {
    const n = el.getAttribute("data-icon");
    if (el.dataset.painted === n) continue;
    el.innerHTML = icon(n);
    el.dataset.painted = n;
  }
}
