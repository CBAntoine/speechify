export function looksLikeChain(name: string, website?: string): boolean {
  const n = name.toLowerCase();
  if (CHAINS.some((c) => n.includes(c))) return true;
  if (website && /\/(locations?|find-a-location|store-locator|offices)\/[^/]+/i.test(website)) return true;
  return false;
}
