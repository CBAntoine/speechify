export function getNiche(id: string | undefined): Niche {
  return NICHES.find((n) => n.id === id) ?? NICHES.find((n) => n.id === "plumber")!;
}

/** Map free text ("dentists", "HVAC", "roofing") to a niche id. */
export function matchNiche(text: string | undefined): Niche | undefined {
  if (!text) return undefined;
  const t = text.toLowerCase().trim();
  return (
    NICHES.find((n) => n.id === t || n.label.toLowerCase() === t || n.plural.toLowerCase() === t) ??
    NICHES.find((n) => t.includes(n.id.replace("_", " ")) || t.includes(n.label.toLowerCase()) || n.plural.toLowerCase().includes(t) || n.query.includes(t))
  );
}

